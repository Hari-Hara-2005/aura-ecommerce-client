export const loadRazorpayScript = () => {
  return new Promise((resolve) => {
    if (window.Razorpay) {
      resolve(true);
      return;
    }
    const script = document.createElement('script');
    script.src = 'https://checkout.razorpay.com/v1/checkout.js';
    script.async = true;
    script.onload = () => resolve(true);
    script.onerror = () => resolve(false);
    document.body.appendChild(script);
  });
};

export const initiateRazorpayPayment = async ({
  keyId,
  orderId, 
  amount,  
  currency = 'INR',
  orderName = 'AURA LUXE',
  description = 'E-commerce Purchase',
  customer = { name: '', email: '', phone: '' },
  onSuccess,
  onFailure,
  onDismiss,
}) => {
  const isLoaded = await loadRazorpayScript();
  if (!isLoaded) {
    const err = new Error('Razorpay SDK failed to load. Please verify your internet connection.');
    console.error(err);
    onFailure?.(err);
    return;
  }

  const razorpayKey = keyId || import.meta.env.VITE_RAZORPAY_KEY_ID;
  if (!razorpayKey) {
    const err = new Error('Razorpay Key ID is not configured. Please provide a valid Razorpay Key.');
    console.error(err);
    onFailure?.(err);
    return;
  }

  if (!orderId) {
    const err = new Error('Missing Razorpay Order ID. Orders must be initiated on the backend first.');
    console.error(err);
    onFailure?.(err);
    return;
  }

  
  const amountInPaise = Number(amount);

  const options = {
    key: razorpayKey,
    amount: amountInPaise,
    currency: currency,
    name: orderName,
    description: description,
    image: 'https://images.unsplash.com/photo-1523275335684-37898b6baf30?w=128&q=80',
    order_id: orderId, // Crucial: must pass the order ID generated by Razorpay Orders API
    handler: function (response) {
      // Real Razorpay callback with cryptographic signature
      onSuccess?.({
        razorpay_payment_id: response.razorpay_payment_id,
        razorpay_order_id: response.razorpay_order_id,
        razorpay_signature: response.razorpay_signature,
      });
    },
    prefill: {
      name: customer.name || '',
      email: customer.email || '',
      contact: customer.phone || '',
    },
    notes: {
      merchant_order_ref: orderName,
    },
    theme: {
      color: '#6366f1',
      backdrop_color: 'rgba(15, 23, 42, 0.85)',
    },
    modal: {
      ondismiss: function () {
        onDismiss?.();
      },
    },
  };

  try {
    const rzp = new window.Razorpay(options);
    rzp.on('payment.failed', function (response) {
      console.error('[Razorpay Payment Failed]:', response.error);
      onFailure?.(response.error);
    });
    rzp.open();
  } catch (err) {
    console.error('[Razorpay initialization error]:', err);
    onFailure?.(err);
  }
};
